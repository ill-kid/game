export function makeCells(list) {
  return list.map((text, index) => {
    let type = 'normal';
    let backSteps = 0;
    let jumpTo = null;
    if (index === 0) type = 'start';
    else if (index === list.length - 1) type = 'end';
    else {
      const back = text.match(/后进\s*(\d+)\s*格/);
      const jump = text.match(/退回(?:到)?\s*(\d+)\s*格/);
      if (back) {
        type = 'special';
        backSteps = Number(back[1]);
      } else if (jump) {
        type = 'special';
        jumpTo = Number(jump[1]);
      } else if (/强制|惩罚|终点|后退|挑战/.test(text)) {
        type = 'special';
      }
    }
    return { text, type, backSteps, jumpTo };
  });
}

